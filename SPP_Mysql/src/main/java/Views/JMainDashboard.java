    private void loadProjects() {
        jPanelGrid.removeAll();
        jPanelGridVertical.removeAll();

        List<ProjectModel> projects = loadProjectsFromDatabase();

        if (projects != null && !projects.isEmpty()) {
            for (ProjectModel project : projects) {
                jProjectCard card = new jProjectCard(project);
                card.setPreferredSize(new java.awt.Dimension(300, 140));
                jPanelGrid.add(card);

                jProjectCard cardVertical = new jProjectCard(project, true);
                cardVertical.setPreferredSize(new java.awt.Dimension(248, 120));
                cardVertical.setMaximumSize(new java.awt.Dimension(248, 120));
                jPanelGridVertical.add(cardVertical);
                jPanelGridVertical.add(javax.swing.Box.createRigidArea(new java.awt.Dimension(0, 10)));
            }

            txtNumProyects.setText(String.valueOf(projects.size()));
            txtPercent.setText(taskController.getAllTaskPercent() + "%");

            int numProjects = projects.size();
            int minHeight = ((numProjects + 2) / 3) * 176 + 50; // 3 cards por fila, 176px por fila (160 + gap)
            jPanelGrid.setPreferredSize(new java.awt.Dimension(jPanelGrid.getWidth(), minHeight));
        }

        jPanelGrid.revalidate();
        jPanelGridVertical.revalidate();
    }


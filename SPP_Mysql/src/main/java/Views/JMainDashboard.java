    public void loadProjectStats(Long projectId) {
        List<TaskModel> tasks = taskController.getTasksByProject(projectId);

        int totalTasks = tasks.size();
        int completed = 0;
        int inProgress = 0;
        int blocked = 0;
        int estimatedHours = 0;

        for (TaskModel task : tasks) {
            if (task.getDurationDays() != null) {
                estimatedHours += task.getDurationDays() * 8;
            }

            switch (task.getStatus()) {
                case HECHO:
                    completed++;
                    break;
                case EN_PROGRESO:
                    inProgress++;
                    break;
                case BLOQUEADO:
                    blocked++;
                    break;
            }
        }

        int workedHours = completed * (estimatedHours / (totalTasks > 0 ? totalTasks : 1));
        String timeRemaining = taskController.calculateTimeRemaining(tasks);
        ProjectModel.Risk risk = projectController.calculateRisk(tasks);

        lblTasksValue.setText(String.valueOf(totalTasks));
        lblCompletedValue.setText(String.valueOf(completed));
        lblInProgressValue.setText(String.valueOf(inProgress));
        lblBlockedValue.setText(String.valueOf(blocked));
        lblEstimatedHoursValue.setText(estimatedHours + "h");
        lblWorkedHoursValue.setText(workedHours + "h");
        lblDaysRemainingValue.setText(timeRemaining);
        lblRiskLevelValue.setText(risk.getDisplayName());
        lblRiskLevelValue.setForeground(risk.getDisplayColor());

        cardCompleted.setBackground(new java.awt.Color(200, 255, 200));
        cardInProgress.setBackground(new java.awt.Color(255, 243, 205));
        cardBlocked.setBackground(new java.awt.Color(255, 200, 200));

        createBarChart(completed, inProgress, blocked, tasks.size() - completed - inProgress - blocked);
    }

    private void createBarChart(int completed, int inProgress, int blocked, int todo) {
        chartCanvas.removeAll();
        chartCanvas.setLayout(new java.awt.BorderLayout());

        javax.swing.JPanel chartPanel = new javax.swing.JPanel() {
            @Override
            protected void paintComponent(java.awt.Graphics g) {
                super.paintComponent(g);
                java.awt.Graphics2D g2d = (java.awt.Graphics2D) g;
                g2d.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING,
                        java.awt.RenderingHints.VALUE_ANTIALIAS_ON);

                int width = getWidth();
                int height = getHeight();
                int padding = 40;
                int barWidth = (width - padding * 2) / 5;

                int total = completed + inProgress + blocked + todo;
                if (total == 0) {
                    total = 1;
                }

                int maxBarHeight = height - padding * 2 - 40;

                int x = padding;
                int[] values = {completed, inProgress, blocked, todo};
                String[] labels = {"Completadas", "En Progreso", "Bloqueadas", "To Do"};
                java.awt.Color[] colors = {
                    new java.awt.Color(34, 139, 34),
                    new java.awt.Color(255, 165, 0),
                    new java.awt.Color(220, 20, 60),
                    new java.awt.Color(100, 149, 237)
                };

                for (int i = 0; i < 4; i++) {
                    int barHeight = (int) ((values[i] / (double) total) * maxBarHeight);
                    int y = height - padding - barHeight - 20;

                    g2d.setColor(colors[i]);
                    g2d.fillRoundRect(x, y, barWidth - 10, barHeight, 8, 8);

                    g2d.setColor(new java.awt.Color(30, 63, 98));
                    g2d.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 16));
                    String value = String.valueOf(values[i]);
                    int valueWidth = g2d.getFontMetrics().stringWidth(value);
                    g2d.drawString(value, x + (barWidth - 10) / 2 - valueWidth / 2, y - 5);

                    g2d.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 10));
                    int labelWidth = g2d.getFontMetrics().stringWidth(labels[i]);
                    g2d.drawString(labels[i], x + (barWidth - 10) / 2 - labelWidth / 2,
                            height - padding + 15);

                    x += barWidth;
                }
            }
        };

        chartPanel.setBackground(java.awt.Color.WHITE);
        chartCanvas.add(chartPanel, java.awt.BorderLayout.CENTER);
        chartCanvas.revalidate();
        chartCanvas.repaint();
    }


    public void loadKanbanTasks(Long projectId) {
        jPanel6.removeAll();
        jPanel7.removeAll();
        jPanel9.removeAll();
        jPanel10.removeAll();

        List<TaskModel> todoTasks = taskController.getTasksByProjectAndStatus(projectId, TaskModel.Status.TODO);
        List<TaskModel> inProgressTasks = taskController.getTasksByProjectAndStatus(projectId, TaskModel.Status.EN_PROGRESO);
        List<TaskModel> blockedTasks = taskController.getTasksByProjectAndStatus(projectId, TaskModel.Status.BLOQUEADO);
        List<TaskModel> doneTasks = taskController.getTasksByProjectAndStatus(projectId, TaskModel.Status.HECHO);

        addTasksToKanbanPanel(jPanel6, todoTasks);
        addTasksToKanbanPanel(jPanel7, inProgressTasks);
        addTasksToKanbanPanel(jPanel9, blockedTasks);
        addTasksToKanbanPanel(jPanel10, doneTasks);
    }

    private void addTasksToKanbanPanel(javax.swing.JPanel panel, List<TaskModel> tasks) {
        panel.setLayout(new javax.swing.BoxLayout(panel, javax.swing.BoxLayout.Y_AXIS));
        for (TaskModel task : tasks) {
            jTaskCard taskCard = new jTaskCard(task, currentProject, this);
            taskCard.setAlignmentX(java.awt.Component.LEFT_ALIGNMENT);
            panel.add(taskCard);
            panel.add(javax.swing.Box.createVerticalStrut(8));
        }
        panel.revalidate();
        panel.repaint();
    }

    public void loadWorkloads(Long projectId) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        List<UserModel> users = userController.getAllUsers();
        List<Object[]> tableData = taskController.getWorkloadTableData(projectId, users);

        for (Object[] row : tableData) {
            model.addRow(row);
        }

        setupTableRenderer();
    }

    private void setupTableRenderer() {
        jTable1.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable table, Object value, boolean isSelected,
                    boolean hasFocus, int row, int column) {

                java.awt.Component cell = super.getTableCellRendererComponent(
                        table, value, isSelected, hasFocus, row, column);

                if (!isSelected) {
                    cell.setBackground(new java.awt.Color(255, 255, 255));
                    cell.setForeground(new java.awt.Color(30, 63, 98));

                    if (column == 4) {
                        String estado = (String) value;
                        if ("Sobreasignado".equals(estado)) {
                            cell.setBackground(new java.awt.Color(255, 200, 200));
                            cell.setForeground(new java.awt.Color(180, 0, 0));
                        } else if ("OK".equals(estado)) {
                            cell.setBackground(new java.awt.Color(200, 255, 200));
                            cell.setForeground(new java.awt.Color(0, 150, 0));
                        }
                    }
                }

                setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
                return cell;
            }
        });
    }

